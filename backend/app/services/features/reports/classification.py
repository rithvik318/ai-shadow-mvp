"""Telling correspondence from noise, before anything expensive reads it.

Deterministic and rule-based on purpose. Roughly a third of a real mailbox is
job-board alerts, invoice robots and newsletters — 300 of 768 messages in one
month of this corpus — and those are recognisable from the sender and the
subject alone. Deciding them here rather than in the analysis stage costs
nothing, is reproducible, and keeps the model's attention on the messages a
manager would actually want described.

The classification is **advisory, and never deletes anything**. A message
marked `AUTOMATED` stays in the `Correspondence` and stays countable; it is
merely not offered as substantive evidence. That distinction matters because
"200 messages arrived, most of them automated" and "200 messages arrived" lead
a reader to different conclusions, and the second is the one the old report
implied.

Business topics are *not* assigned here. A rule that sorted "Invoice 4021" into
finance would be guessing from a word, and a workstream inferred from a subject
line is exactly the fabrication this pipeline is arranged to avoid. Topic
belongs to the analysis stage, which reads whole threads and cites the messages
it drew from.
"""

from __future__ import annotations

import re
from enum import StrEnum

from app.services.features.reports.correspondence import Direction, Message

#: Senders whose local part announces that nobody typed the message.
_ROBOT_LOCAL_PARTS = frozenset(
    {
        "noreply",
        "no-reply",
        "donotreply",
        "do-not-reply",
        "notification",
        "notifications",
        "alerts",
        "alert",
        "mailer-daemon",
        "postmaster",
        "bounce",
        "bounces",
        "newsletter",
        "news",
        "updates",
        "automated",
        "system",
        "support@github",
    }
)

#: Phrases that only appear in bulk mail. Matched against the subject and the
#: first part of the body, which is where a list footer or a marketing header
#: sits.
_BULK_MARKERS = (
    "unsubscribe",
    "view this email in your browser",
    "manage your preferences",
    "you are receiving this email because",
    "this is an automated message",
    "do not reply to this email",
    "update your email preferences",
)

_SUBJECT_NOISE = (
    "out of office",
    "automatic reply",
    "undeliverable",
    "delivery has failed",
    "your daily digest",
    "weekly digest",
    "newsletter",
    "webinar",
    "invitation to connect",
    "password reset",
    "verify your email",
    "security alert",
    "new sign-in",
)

#: Free mail and social hosts never carry a company's own automation, so a
#: person writing from one is a person. Kept short deliberately: the list is a
#: safety net against over-eager robot detection, not a directory.
_HUMAN_DOMAINS = frozenset(
    {"gmail.com", "outlook.com", "hotmail.com", "yahoo.com", "icloud.com", "me.com"}
)


class MessageClass(StrEnum):
    """What kind of message this is, as far as sender and shape can say."""

    #: Written by a person, to or from a person. The report's raw material.
    SUBSTANTIVE = "substantive"
    #: Generated by a system: alerts, receipts, job boards, delivery reports.
    AUTOMATED = "automated"
    #: Bulk mail a person nominally sent: newsletters, marketing, digests.
    BULK = "bulk"


def _local_part(address: str) -> str:
    local, _, _ = address.partition("@")

    return local.lower()


def _looks_robotic(message: Message) -> bool:
    sender = message.sender

    if sender is None:
        return True

    local = _local_part(sender.address)

    if local in _ROBOT_LOCAL_PARTS:
        return True

    # `jobs-noreply@`, `billing-no-reply@` and friends.
    return any(marker in local for marker in ("noreply", "no-reply", "donotreply"))


def _has_bulk_marker(message: Message) -> bool:
    haystack = f"{message.subject}\n{message.body[:1500]}".lower()

    return any(marker in haystack for marker in _BULK_MARKERS)


def _subject_is_noise(message: Message) -> bool:
    subject = message.subject.lower()

    return any(marker in subject for marker in _SUBJECT_NOISE)


def classify(message: Message) -> MessageClass:
    """Decide what one message is. Never consults a model.

    Anything the owner sent is substantive without further examination: a
    person sat down and wrote it, and an outbound message is the strongest
    evidence a report has that work was done.
    """

    if message.direction is Direction.OUTBOUND:
        return MessageClass.SUBSTANTIVE

    if _looks_robotic(message):
        return MessageClass.AUTOMATED

    if _subject_is_noise(message):
        return MessageClass.AUTOMATED

    if _has_bulk_marker(message):
        return MessageClass.BULK

    return MessageClass.SUBSTANTIVE


_ORG_SUFFIXES = re.compile(r"\.(com|net|org|io|co|gov|edu|ai|uk|in)(\.[a-z]{2})?$")


def organisation_of(domain: str) -> str | None:
    """A readable organisation name from an email domain, or None.

    `sunradia.com` becomes "Sunradia". A free-mail domain returns None rather
    than "Gmail", because a person's mail host is not an organisation and
    listing one as a stakeholder organisation would be wrong on the page.
    """

    cleaned = (domain or "").strip().lower()

    if not cleaned or cleaned in _HUMAN_DOMAINS:
        return None

    stem = _ORG_SUFFIXES.sub("", cleaned)
    leaf = stem.split(".")[-1] if stem else ""

    return leaf.replace("-", " ").title() or None
